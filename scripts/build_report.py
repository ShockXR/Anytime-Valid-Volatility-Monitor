"""Assemble docs/experiment_report.md from docs/report_parts/.

Each experiment keeps its own section in ``docs/report_parts/<ID>.md`` (written by
whoever ran it). This script puts them in a fixed order behind a short header, so
the report never drifts from its parts. Run from the repository root:

    python scripts/build_report.py              # parts as they are in the working tree
    python scripts/build_report.py --committed  # parts as committed at HEAD (ignores
                                                # unfinished or uncommitted parts)
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARTS = ROOT / "docs" / "report_parts"
OUT = ROOT / "docs" / "experiment_report.md"

ORDER = ["_header", "E01_E05", "E6", "E7", "E8", "E9", "E10", "E11", "E12", "E13", "E14", "E15", "E16", "E17", "E18", "E19", "E20", "E21", "TH4", "TH5", "TH6",
         "_alternatives", "ALT1", "ALT2", "ALT3", "ALT4", "ALT5", "ALT6", "_footer"]


COMMITTED = "--committed" in sys.argv[1:]


def committed_parts() -> set:
    out = subprocess.run(["git", "ls-tree", "--name-only", "HEAD", "docs/report_parts/"], cwd=ROOT,
                         capture_output=True, text=True, check=True).stdout.split()
    return {Path(p).stem for p in out if p.endswith(".md")}


def read_part(name: str) -> str:
    if COMMITTED:
        text = subprocess.run(["git", "show", f"HEAD:docs/report_parts/{name}.md"], cwd=ROOT,
                              capture_output=True, text=True, check=True).stdout.strip()
    else:
        text = (PARTS / f"{name}.md").read_text().strip()
    lines = text.splitlines()
    for k, line in enumerate(lines):  # one level-1 title per report: demote titles of parts
        if line.startswith("# ") and not name.startswith("_header"):
            lines[k] = "#" + line
    return "\n".join(lines)


def main() -> None:
    present = committed_parts() if COMMITTED else {p.stem for p in PARTS.glob("*.md")}
    names = [n for n in ORDER if n in present] + sorted(present - set(ORDER))
    body = "\n\n---\n\n".join(read_part(n) for n in names)
    note = "<!-- Generated by scripts/build_report.py from docs/report_parts/. Edit the parts, not this file. -->\n\n"
    OUT.write_text(note + body + "\n")
    missing = [n for n in ORDER if n not in present and not n.startswith("_")]
    print(f"wrote {OUT.relative_to(ROOT)} from {len(names)} parts; not yet available: {', '.join(missing) or 'none'}")


if __name__ == "__main__":
    main()
