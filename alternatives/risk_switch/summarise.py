"""Render the markdown tables used in RESULTS.md from the CSV files in results/.

Run after ``run_experiment.py``. Writes ``results/summary_tables.md``. Every
number quoted in RESULTS.md is copied from that file.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

OUT = Path(__file__).resolve().parent / "results"

ROLE_ORDER = ["buy_and_hold", "ewma_minute", "ewma_hour", "ewma_day", "robust_roll", "switch_robust", "switch_gaussian"]
ROLE_LABEL = dict(buy_and_hold="buy and hold", ewma_minute="EWMA targeting, minute", ewma_hour="EWMA targeting, hour",
                  ewma_day="EWMA targeting, day", robust_roll="robust rolling, day", switch_robust="switch, robust monitor",
                  switch_gaussian="switch, Gaussian LR monitor")


def md(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, row in df.iterrows():
        cells = []
        for c in cols:
            v = row[c]
            if isinstance(v, (float, np.floating)):
                cells.append("" if np.isnan(v) else floatfmt.format(v))
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def pct(x):
    return "" if pd.isna(x) else f"{100 * x:.1f}%"


def risk_table(df: pd.DataFrame, with_ci: bool) -> pd.DataFrame:
    rows = []
    for role in ROLE_ORDER:
        r = df[df.role == role]
        if r.empty:
            continue
        r = r.iloc[0] if len(r) == 1 else r.mean(numeric_only=True)
        d = {
            "rule": ROLE_LABEL[role] + (" (over budget)" if bool(r.get("over_budget", False)) else ""),
            "realised vol": pct(r["realised_vol"]),
            "tracking RMS": "" if pd.isna(r["tracking_rms"]) else f"{r['tracking_rms']:.3f}",
            "vol of vol": f"{r['vol_of_vol']:.3f}",
            "max drawdown": pct(r["max_drawdown"]),
            "worst day": pct(r["worst_day"]),
            "Sharpe": f"{r['sharpe']:.2f}" + (f" [{r['sharpe_lo']:.2f}, {r['sharpe_hi']:.2f}]" if with_ci and "sharpe_lo" in r else ""),
            "mean exposure": f"{r['mean_exposure']:.2f}",
            "turnover / yr": f"{r['turnover_per_year']:.1f}",
            "trades / yr": f"{r['trades_per_year']:.0f}",
            "cost drag / yr": pct(r["cost_drag_per_year"]),
        }
        rows.append(d)
    return pd.DataFrame(rows)


def main():
    parts = []
    params = pd.read_json(OUT / "frozen_parameters.json", typ="series")
    chosen = params["chosen"]
    parts.append("# Summary tables (generated by summarise.py from results/*.csv) [REAL]\n")
    parts.append("Frozen choices: " + ", ".join(f"{k} = `{v}`" for k, v in chosen.items()) +
                 f". Robust-to-sd factor k = {params['robust_to_sd']:.4f} (per coin: " +
                 ", ".join(f"{k} {v:.3f}" for k, v in params["robust_to_sd_per_coin"].items()) + ").\n")

    # T1 alarms
    a = pd.read_csv(OUT / "alarms_crypto.csv")
    t = a.groupby(["period", "monitor", "false_alarm", "band"])["alarms_per_year"].mean().reset_index()
    t = t.pivot_table(index=["monitor", "false_alarm", "band"], columns="period", values="alarms_per_year").reset_index()
    n = pd.read_csv(OUT / "alarms_nifty.csv")
    t = t.merge(n[["monitor", "false_alarm", "band", "alarms_per_year", "up", "down"]].rename(
        columns={"alarms_per_year": "Nifty 2017 to 2026", "up": "Nifty up", "down": "Nifty down"}), on=["monitor", "false_alarm", "band"], how="left")
    t["false_alarm"] = t["false_alarm"].map(lambda v: f"{100 * v:g}%")
    t["band"] = t["band"].map(lambda v: f"{v:g}")
    t = t.rename(columns={"false_alarm": "false alarm budget", "2024_IS": "crypto 2024 (mean of 5 coins)", "2025_OOS": "crypto 2025 (mean of 5 coins)"})
    parts.append("## T1. Alarms per year\n\n" + md(t, "{:.1f}") + "\n")

    # T2 in-sample selection
    s = pd.read_csv(OUT / "is_selection_crypto_2024.csv")
    s = s.sort_values(["family", "tracking_rms"])
    t = s[["strategy", "tracking_rms", "realised_vol", "max_drawdown", "worst_day", "sharpe", "turnover_per_year", "trades_per_year", "cost_drag_per_year", "eligible", "chosen"]].copy()
    for c in ("realised_vol", "max_drawdown", "worst_day", "cost_drag_per_year"):
        t[c] = t[c].map(pct)
    t = t.rename(columns={"tracking_rms": "tracking RMS", "realised_vol": "realised vol", "max_drawdown": "max drawdown",
                          "worst_day": "worst day", "turnover_per_year": "turnover / yr", "trades_per_year": "trades / yr",
                          "cost_drag_per_year": "cost drag / yr", "eligible": "within 2% budget"})
    parts.append("## T2. In-sample grid, 2024 crypto, mean over the five coins (selection sample)\n\n" + md(t, "{:.3f}") + "\n")

    # T3 crypto OOS per role, mean over coins, and EW5
    f = pd.read_csv(OUT / "frozen_crypto.csv")
    for period, label in (("2024_IS", "2024 (tuning sample)"), ("2025_OOS", "2025 (out of sample)")):
        sub = f[(f.period == period) & (f.asset != "EW5")]
        parts.append(f"## T3{'a' if period == '2024_IS' else 'b'}. Crypto {label}: mean of the five coins\n\n" + md(risk_table(sub, False)) + "\n")
        ew = f[(f.period == period) & (f.asset == "EW5")]
        parts.append(f"## T3{'c' if period == '2024_IS' else 'd'}. Crypto {label}: equal-weight portfolio of the five coins (bootstrap 95% intervals)\n\n" + md(risk_table(ew, True)) + "\n")

    # T4 per coin 2025: tracking, MDD, worst day, Sharpe per role
    sub = f[(f.period == "2025_OOS")]
    for metric, fmt in (("tracking_rms", "{:.3f}"), ("max_drawdown", "pct"), ("worst_day", "pct"), ("sharpe", "{:.2f}"), ("trades_per_year", "{:.0f}")):
        p = sub.pivot(index="asset", columns="role", values=metric)[[r for r in ROLE_ORDER if r in sub.role.unique()]]
        p = p.rename(columns=ROLE_LABEL).reset_index()
        if fmt == "pct":
            for c in p.columns[1:]:
                p[c] = p[c].map(pct)
            parts.append(f"### T4. Crypto 2025 by coin: {metric.replace('_', ' ')}\n\n" + md(p) + "\n")
        else:
            parts.append(f"### T4. Crypto 2025 by coin: {metric.replace('_', ' ')}\n\n" + md(p, fmt) + "\n")

    # T5 Sharpe differences
    for name, fn in (("crypto 2025", "sharpe_diff_crypto_2025.csv"), ("Nifty 2017 to 2026", "sharpe_diff_nifty.csv")):
        d = pd.read_csv(OUT / fn)
        d["role"] = d["strategy"].map({v: k for k, v in chosen.items()})
        d["rule"] = d["role"].map(ROLE_LABEL)
        d["Sharpe [95% CI]"] = d.apply(lambda r: f"{r['sharpe']:.2f} [{r['sharpe_lo']:.2f}, {r['sharpe_hi']:.2f}]", axis=1)
        d["difference vs EWMA day [95% CI]"] = d.apply(lambda r: f"{r['diff']:+.2f} [{r['diff_lo']:+.2f}, {r['diff_hi']:+.2f}]", axis=1)
        d = d[d.role != "ewma_day"]
        parts.append(f"## T5. Sharpe ratios and paired differences against daily EWMA targeting, {name} (block bootstrap, base cost)\n\n" +
                     md(d[["asset", "rule", "Sharpe [95% CI]", "difference vs EWMA day [95% CI]"]]) + "\n")

    # T6 Nifty frozen
    nf = pd.read_csv(OUT / "frozen_nifty.csv")
    parts.append("## T6. Nifty 50, June 2017 to October 2026 (out of sample, bootstrap 95% intervals)\n\n" + md(risk_table(nf, True)) + "\n")
    by = pd.read_csv(OUT / "frozen_nifty_by_year.csv")
    for metric, fmt in (("realised_vol", "pct"), ("max_drawdown", "pct"), ("worst_day", "pct"), ("tracking_rms", "{:.3f}"), ("ann_return", "pct")):
        p = by.pivot(index="period", columns="role", values=metric)[[r for r in ROLE_ORDER if r in by.role.unique()]].rename(columns=ROLE_LABEL).reset_index().rename(columns={"period": "year"})
        p["year"] = p["year"].astype(int).astype(str)
        if fmt == "pct":
            for c in p.columns[1:]:
                p[c] = p[c].map(pct)
            parts.append(f"### T7. Nifty by calendar year: {metric.replace('_', ' ')}\n\n" + md(p) + "\n")
        else:
            parts.append(f"### T7. Nifty by calendar year: {metric.replace('_', ' ')}\n\n" + md(p, fmt) + "\n")

    # T8 cost sensitivity
    for name, fn in (("crypto equal-weight portfolio, 2025", "cost_sensitivity_crypto_2025.csv"), ("Nifty 50, 2017 to 2026", "cost_sensitivity_nifty.csv")):
        cs = pd.read_csv(OUT / fn)
        for metric, fmt in (("sharpe", "{:.2f}"), ("ann_return", "pct")):
            p = cs.pivot(index="role", columns="cost_bps", values=metric).loc[[r for r in ROLE_ORDER if r in cs.role.unique()]]
            p.columns = [f"{c:g} bp" for c in p.columns]
            p = p.reset_index()
            p["role"] = p["role"].map(ROLE_LABEL)
            p = p.rename(columns={"role": "rule"})
            if fmt == "pct":
                for c in p.columns[1:]:
                    p[c] = p[c].map(pct)
                parts.append(f"### T8. Cost sensitivity, {name}: net annual return\n\n" + md(p) + "\n")
            else:
                parts.append(f"### T8. Cost sensitivity, {name}: net Sharpe ratio\n\n" + md(p, fmt) + "\n")

    text = "\n".join(parts)
    (OUT / "summary_tables.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
